const token = () => crypto.randomUUID().replaceAll('-', '').slice(0, 8);
test('the default creation form applies hidden status, priority and point defaults without a form change', async ({ page }) => {
  await page.goto('./#tasks'); const before = await api<ManiphestConfiguration>(page, '/maniphest/config');
  const write = (config: ManiphestConfiguration['config']) => ({ expectedVersion: config.version, statuses: config.statuses, priorities: config.priorities, fields: config.fields, forms: config.forms });
  try {
    const configured = structuredClone(before.config);
    configured.forms = configured.forms.map(form => form.key === 'default' ? { ...form, fields: ['description', 'ownerId', 'projectIds'], defaults: { status: 'resolved', priority: 'urgent', points: 13.5 } } : form);
    await api(page, '/maniphest/config', write(configured), 'PUT'); await page.reload();
    await page.getByRole('button', { name: 'Create Task', exact: true }).click(); const dialog = page.getByRole('dialog');
    await expect(dialog.getByLabel('Status', { exact: true })).toHaveCount(0);
    await dialog.getByLabel('Title', { exact: true }).fill(`Default form ${token()}`);
    const created = page.waitForResponse(response => response.url().endsWith('/api/tasks') && response.request().method() === 'POST');
    await dialog.getByRole('button', { name: 'Create Task', exact: true }).click();
    expect(await (await created).json()).toMatchObject({ status: 'resolved', statusClosed: true, priority: 'urgent', points: 13.5 });
    await expect(dialog).not.toBeVisible();
  } finally { const latest = await api<ManiphestConfiguration>(page, '/maniphest/config'); await api(page, '/maniphest/config', write({ ...before.config, version: latest.config.version }), 'PUT'); }
});
