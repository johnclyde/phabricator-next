test('bulk preview rejects a stale task without partially changing other tasks', async ({ page }) => {
  await page.goto('./#tasks'); const key = token();
  const first = await api<Task>(page, '/tasks', { title: `Bulk stale ${key} first` });
  const second = await api<Task>(page, '/tasks', { title: `Bulk stale ${key} second` });
  await page.reload(); await page.getByLabel('Search workspace', { exact: true }).fill(`Bulk stale ${key}`);
  await page.getByRole('tab', { name: 'Bulk Edit', exact: true }).click();
  await page.getByRole('button', { name: 'Select visible editable tasks', exact: true }).click();
  await page.getByLabel('Bulk value', { exact: true }).selectOption('resolved');
  await page.getByRole('button', { name: 'Preview Bulk Edit', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Bulk edit preview', exact: true })).toContainText('Review 2 task changes');
  await api(page, `/tasks/${second.id}`, { expectedVersion: second.version, title: `${second.title} edited elsewhere` }, 'PATCH');
  await page.getByRole('button', { name: 'Apply Reviewed Bulk Edit', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText(/changed|conflict/i);
  expect((await api<TaskDetail>(page, `/tasks/${first.id}`)).task.status).toBe('open');
  expect((await api<TaskDetail>(page, `/tasks/${second.id}`)).task.status).toBe('open');
});

test('an unknown bulk response retries the exact operation once after reload', async ({ page }) => {
  await page.goto('./#tasks'); const key = token();
  const task = await api<Task>(page, '/tasks', { title: `Bulk recovery ${key}`, points: 2 });
  await page.reload(); await page.getByLabel('Search workspace', { exact: true }).fill(`Bulk recovery ${key}`);
  await page.getByRole('tab', { name: 'Bulk Edit', exact: true }).click();
  await page.getByRole('button', { name: 'Select visible editable tasks', exact: true }).click();
  await page.getByLabel('Bulk field', { exact: true }).selectOption('points'); await page.getByLabel('Bulk value', { exact: true }).fill('8');
  await page.getByRole('button', { name: 'Preview Bulk Edit', exact: true }).click();
  let first = true; const bodies: unknown[] = [], keys: string[] = [];
  await page.route('**/api/maniphest/bulk', async route => { bodies.push(route.request().postDataJSON()); keys.push(route.request().headers()['idempotency-key']!); if (first) { first = false; const response = await route.fetch(); expect(response.ok()).toBe(true); await route.abort('failed'); } else await route.continue(); });
  await page.getByRole('button', { name: 'Apply Reviewed Bulk Edit', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Retry Exact Request', exact: true })).toBeVisible();
  await page.reload(); await page.getByRole('tab', { name: 'Bulk Edit', exact: true }).click();
  await page.getByRole('button', { name: 'Retry Exact Request', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Retry Exact Request', exact: true })).toHaveCount(0);
  expect(keys).toHaveLength(2); expect(keys[1]).toBe(keys[0]); expect(bodies[1]).toEqual(bodies[0]);
  const detail = await api<TaskDetail>(page, `/tasks/${task.id}`); expect(detail.task.points).toBe(8); expect(detail.task.version).toBe(task.version + 1);
});
