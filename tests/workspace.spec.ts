import { test, expect } from '@playwright/test';

test('tasks persist across reloads and typed commands navigate on desktop and mobile', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#tasks');
  await expect(page.getByRole('heading', { name: 'Maniphest', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create Task', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const title = `Persistent ${info.project.name} task ${Date.now()}`;
  await dialog.getByLabel('Title', { exact: true }).fill(title);
  await dialog.getByLabel('Description', { exact: true }).fill('Verify persisted workflow and mobile touch controls.');
  await dialog.getByRole('button', { name: 'Create Task', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
  await page.reload();
  const status = page.getByRole('combobox', { name: new RegExp(`Status of .*${title}`) });
  await status.selectOption('resolved');
  await expect(status).toHaveValue('resolved');
  await page.reload();
  await expect(status).toHaveValue('resolved');
  await page.getByRole('button', { name: 'Voice and commands', exact: true }).click();
  await page.getByRole('textbox', { name: 'Workspace command', exact: true }).fill('open drafts');
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Drafts', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});

test('prose revisions preserve word diffs, comments and invalidate old acceptance', async ({ page }, info) => {
  await page.goto('/#drafts');
  await page.getByRole('button', { name: 'Create Draft', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const title = `Reviewable ${info.project.name} argument ${Date.now()}`;
  await dialog.getByLabel('Title', { exact: true }).fill(title);
  await dialog.getByRole('textbox', { name: /^Draft text/ }).fill('The applicant requests a short extension.\n');
  await dialog.getByRole('button', { name: 'Create Draft', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1 })).toContainText(title);
  await page.getByRole('button', { name: 'Run Local Checks', exact: true }).click();
  await expect(page.getByText(/Local text checks completed for 1 file/)).toBeVisible();
  await page.getByRole('combobox', { name: 'Revision status', exact: true }).selectOption('accepted');
  await expect(page.getByRole('combobox', { name: 'Revision status', exact: true })).toHaveValue('accepted');
  await page.getByRole('button', { name: 'Discussion', exact: false }).click();
  await page.getByRole('textbox', { name: 'Review comment', exact: true }).fill('Please make the requested duration precise.');
  await page.getByRole('button', { name: 'Add Comment', exact: true }).click();
  await expect(page.getByText('Please make the requested duration precise.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit & add version', exact: true }).click();
  await page.getByRole('textbox', { name: 'File content', exact: true }).fill('The applicant requests a seven-day extension.\n');
  await page.getByRole('textbox', { name: 'What changed?', exact: true }).fill('Specify the duration.');
  await page.getByRole('button', { name: 'Save New Version', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Revision status', exact: true })).toHaveValue('needs_review');
  await expect(page.locator('.prose-content ins')).toContainText('seven-day');
  await expect(page.locator('.prose-content del')).toContainText('short');
  await expect(page.getByRole('combobox', { name: 'Revision status', exact: true }).locator('option[value="accepted"]')).toHaveJSProperty('disabled', true);
  await page.getByRole('button', { name: 'Discussion', exact: false }).click();
  await expect(page.getByText('Please make the requested duration precise.', { exact: true })).not.toBeVisible();
  await page.getByLabel('Version to inspect', { exact: true }).selectOption('1');
  await expect(page.getByText('Please make the requested duration precise.', { exact: true })).toBeVisible();
  await page.getByLabel('Version to inspect', { exact: true }).selectOption('2');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `.data/${info.project.name}-review.png`, fullPage: true });
});

test('first-visit shell works offline and queued edits replay exactly once', async ({ page, context }, info) => {
  await page.goto('/#tasks');
  await expect(page.getByRole('heading', { name: 'Maniphest', exact: true })).toBeVisible();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Maniphest', exact: true })).toBeVisible();
  await expect(page.getByText('Viewing the last saved snapshot.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Create Task', exact: true }).click();
  const title = `Offline ${info.project.name} task ${Date.now()}`;
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Title', { exact: true }).fill(title);
  await dialog.getByRole('button', { name: 'Create Task', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /Offline outbox, 1 pending/ }).click();
  await expect(page.getByRole('heading', { name: 'Pending changes', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Task created', exact: true })).toHaveCount(1);
  await context.setOffline(false);
  await expect(page.getByText('Everything is synchronized.', { exact: false })).toBeVisible();
  await page.goto('/#tasks');
  await expect(page.getByText(title, { exact: true })).toHaveCount(1);
  await page.reload();
  await expect(page.getByText(title, { exact: true })).toHaveCount(1);
});
