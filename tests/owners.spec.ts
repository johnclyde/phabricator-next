    await bob.page.goto(`./#owners/${pkg.id}`);
    await expect(bob.page.getByRole('heading', { name, exact: true })).toBeVisible();
    await expect(bob.page.getByRole('button', { name: 'Edit package', exact: true })).toHaveCount(0);
